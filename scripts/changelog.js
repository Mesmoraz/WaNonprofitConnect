// The change log, one file per entry: roadmap/changelog/YYYY-MM-DD-NN-short-title.md (NN orders entries on the same
// day, 01 first). One file each means two pull requests never edit the same lines. This joins them newest first.
//   node scripts/changelog.js          writes roadmap/CHANGELOG.md (not committed) and prints the newest entry
//   node scripts/changelog.js --check  fails if a file is misnamed or doesn't start with "## YYYY-MM-DD · "
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const dir = path.join(root, 'roadmap', 'changelog');
const NAME = /^(\d{4}-\d{2}-\d{2})-(\d{2})-[a-z0-9-]+\.md$/;

const files = fs.readdirSync(dir).filter(f => f.endsWith('.md')).sort().reverse();   // newest first
const problems = [];
const entries = files.map(f => {
  const m = f.match(NAME);
  const text = fs.readFileSync(path.join(dir, f), 'utf8').replace(/\r\n/g, '\n').trim();
  if (!m) problems.push(`${f}: name it YYYY-MM-DD-NN-short-title.md`);
  else if (!text.startsWith(`## ${m[1]} · `)) problems.push(`${f}: the first line should be "## ${m[1]} · <what changed>"`);
  return text;
});
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
if (process.argv.includes('--check')) { console.log(`${files.length} change log entries, all well formed`); process.exit(0); }

const head = '# Change log\n\nNewest first. Generated by `node scripts/changelog.js` from `roadmap/changelog/`, one file per entry; don\'t edit this file. Rules: `SDLC.md`, section "Change log and test cases".\n\n---\n\n';
fs.writeFileSync(path.join(root, 'roadmap', 'CHANGELOG.md'), head + entries.join('\n\n---\n\n') + '\n');
console.log(`roadmap/CHANGELOG.md: ${entries.length} entries. Newest: ${entries[0].split('\n')[0].slice(3)}`);
