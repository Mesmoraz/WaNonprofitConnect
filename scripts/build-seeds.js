// Builds the prototype's seed block from docs/seeds/*.json and injects it into
// docs/helpbook-prototype.html between the SEEDS markers. The prototype's data is
// generated, never hand-edited (roadmap/SDLC.md, "Keeping designs uncoupled").
//
//   node scripts/build-seeds.js
//
// WHICH SCHOOLS GET EMBEDDED: edit LEVELS below. Every level OSPI publishes is already
// normalized in docs/seeds/schools.json, and higher education (universities, community and
// technical colleges) comes from docs/seeds/highered.json. Turning a level on is a one-line
// change here; nothing in the app keys off the level, only off type 'school'.
//
//   district   335 rows,  ~32 KB    (always on: every district in the state)
//   high       520 rows,  ~54 KB
//   middle     370 rows,  ~37 KB
//   elementary 1144 rows, ~110 KB
//   k12        157 rows,  ~15 KB
//   other      307 rows,  ~29 KB
//   university/college  from highered.json when present, ~5 KB
//
// All of them together is ~280 KB on top of the app, which still opens fine but makes the
// single-file prototype heavy to edit. Add levels when a round needs them.
const fs = require('fs');
const path = require('path');

const LEVELS = ['district', 'high', 'university', 'college'];

const root = path.resolve(__dirname, '..');
const seeds = p => { const f = path.join(root, 'docs', 'seeds', p); return fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, 'utf8')) : null; };
const proto = path.join(root, 'docs', 'helpbook-prototype.html');
const BEGIN = '// --- SEEDS:BEGIN (generated by scripts/build-seeds.js; do not edit by hand) ---';
const END = '// --- SEEDS:END ---';

// OSPI's GradeCategory-derived sub -> our level
const LEVEL_OF = { 'District': 'district', 'High school': 'high', 'Middle school': 'middle', 'Elementary school': 'elementary', 'K-12': 'k12', 'Other': 'other' };
const j = v => JSON.stringify(v);
const org = o => `{...EX,ein:${j(o.ein)},name:${j(o.name)},city:${j(o.city)},zip:${j(o.zip || '')},type:${j(o.type)},sub:${j(o.sub)}` +
  (o.domain ? `,domain:${j(o.domain)}` : '') + (o.level ? `,level:${j(o.level)}` : '') +
  (o.lat != null ? `,lat:${+o.lat.toFixed(4)},lon:${+o.lon.toFixed(4)}` : '') +
  (o.needTags && o.needTags.length ? `,needTags:${j(o.needTags)}` : '') +
  (o.haveTags && o.haveTags.length ? `,haveTags:${j(o.haveTags)}` : '') + '}';

const rows = [];
const counts = {};
const add = (o, level) => { rows.push(org({ ...o, level })); counts[level] = (counts[level] || 0) + 1; };

// --- Schools and districts (OSPI) ---
const schools = seeds('schools.json');
if (schools) {
  if (LEVELS.includes('district')) for (const d of schools.districts) add({ ein: d.id, name: d.name, city: d.city, zip: d.zip, type: 'school', sub: 'District', lat: d.lat, lon: d.lon }, 'district');
  for (const s of schools.schools) {
    const level = LEVEL_OF[s.sub] || 'other';
    if (LEVELS.includes(level)) add({ ein: s.id, name: s.name, city: s.city, zip: s.zip, type: 'school', sub: s.sub, lat: s.lat, lon: s.lon }, level);
  }
}

// --- Higher education (universities, community and technical colleges) ---
const he = seeds('highered.json');
if (he) for (const i of he.institutions) {
  const level = i.level || 'university';
  if (LEVELS.includes(level)) add({ ein: i.id, name: i.name, city: i.city, zip: i.zip, type: 'school', sub: i.sub, domain: i.domain, lat: i.lat, lon: i.lon }, level);
}

// --- Workforce boards and centers ---
const wf = seeds('workforce.json');
if (wf) {
  for (const b of wf.boards) add({ ein: b.id, name: b.name, city: b.city, zip: b.zip, type: 'workforce', sub: b.sub, domain: b.domain, lat: b.lat, lon: b.lon, needTags: b.needTags }, 'workforce');
  for (const c of wf.centers) add({ ein: c.id, name: c.name, city: c.city, zip: c.zip, type: 'workforce', sub: c.sub, domain: c.domain, lat: c.lat, lon: c.lon }, 'workforce');
}

// --- Foundations (real, EINs verified; kept here so every kind comes from one generated block) ---
const FOUNDATIONS = [
  { ein: '916013536', name: 'Seattle Foundation', city: 'SEATTLE', zip: '98101', sub: 'Community foundation', domain: 'seattlefoundation.org' },
  { ein: '562618866', name: 'Bill & Melinda Gates Foundation', city: 'SEATTLE', zip: '98109', sub: 'Private foundation', domain: 'gatesfoundation.org' },
  { ein: '911726410', name: 'Whatcom Community Foundation', city: 'BELLINGHAM', zip: '98225', sub: 'Community foundation', domain: 'whatcomcf.org' },
  { ein: '910941053', name: 'Innovia Foundation', city: 'SPOKANE', zip: '99201', sub: 'Community foundation', domain: 'innovia.org' },
  { ein: '943121390', name: 'Community Foundation of South Puget Sound', city: 'OLYMPIA', zip: '98501', sub: 'Community foundation', domain: 'thecommunityfoundation.com' },
];
for (const f of FOUNDATIONS) add({ ...f, type: 'foundation', haveTags: ['grants'] }, 'foundation');

// --- People (invented; see docs/seeds/demo.json) ---
const demo = seeds('demo.json');
if (demo) for (const p of demo.people) add({ ein: p.id, name: p.name, city: p.city, zip: p.zip, type: 'person', sub: 'Person', haveTags: p.can }, 'person');

// --- Needs and offers, the retags, the Together initiative, and the grants ---
const L = l => `L(${l.id},${j(l.kind)},${j(l.ein)},${j(l.category)},${j(l.title)},${j(l.desc || '')},${l.qty ?? 'null'},${j(l.unit || '')},${j(l.urgency)},${j(l.tags || '')},d(${l.hoursAgo}),${j(l.cadence || 'One-time')},${j(l.help)})`;
const listings = demo ? demo.listings.map(L).join(',\n    ') : '';
const retag = demo ? j(demo.retag) : '[]';
const together = demo && demo.together ? j(demo.together) : 'null';
const grantsFile = seeds('grants.json');
const grants = grantsFile ? j(grantsFile.grants) : '[]';

const block = `${BEGIN}
// Schools and districts: OSPI. Workforce: WA Workforce Board and WorkSource. Higher education: SBCTC and
// the institutions. Foundations: IRS. People, needs, offers and the initiative: invented for the demo.
// Levels embedded: ${LEVELS.join(', ')}. Change LEVELS in scripts/build-seeds.js and re-run.
const EX = { cause:'S', inc:'', rev:0, ruling:'', filing:'', needTags:[], haveTags:[] };
ORGS.push(
  ${rows.join(',\n  ')}
);
ORGS.find(o => o.ein === '911428805').domain = 'ballardfoodbank.org';
const SEED_LISTINGS = () => { const d = h => new Date(Date.now() - h * 3600e3).toISOString(); return [
    ${listings}
  ]; };
const SEED_RETAG = ${retag};
const SEED_TOGETHER = ${together};
const GRANTS = ${grants};
${END}`;

let html = fs.readFileSync(proto, 'utf8');
const i = html.indexOf(BEGIN), k = html.indexOf(END);
if (i < 0 || k < 0) { console.error('SEEDS markers not found in docs/helpbook-prototype.html'); process.exit(1); }
html = html.slice(0, i) + block + html.slice(k + END.length);
fs.writeFileSync(proto, html);

const total = Object.values(counts).reduce((a, b) => a + b, 0);
console.log('Seed block rebuilt. Levels:', LEVELS.join(', '));
for (const [k2, v] of Object.entries(counts)) console.log(`  ${k2.padEnd(12)} ${v}`);
console.log(`  ${'total orgs'.padEnd(12)} ${total}`);
console.log(`  ${'listings'.padEnd(12)} ${demo ? demo.listings.length : 0}  grants ${grantsFile ? grantsFile.grants.length : 0}`);
console.log('  block size', (block.length / 1024).toFixed(0) + ' KB');
